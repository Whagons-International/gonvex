const PROJECT = "whagons";
const meta = summary as { artifactHash: string; generation: number };
const json = (value: unknown, status = 200) => new Response(JSON.stringify(value), { status, headers: { "content-type": "application/json" } });
const message = (error: unknown) => String((error as Error)?.message ?? error);

/** Rows read and written by every `exec` on the wrapped handle (the path's direct reads: receipts, clock). */
function countingSql(inner: SqlStorage): { sql: SqlStorage; take(): { statements: number; rowsRead: number; rowsWritten: number } } {
  let cursors: SqlStorageCursor<Record<string, SqlStorageValue>>[] = [];
  const sql = new Proxy(inner, {
    get(target, property) {
      if (property === "exec") {
        return (query: string, ...bindings: unknown[]) => {
          const cursor = target.exec(query, ...bindings);
          cursors.push(cursor);
          return cursor;
        };
      }
      const value = Reflect.get(target, property, target) as unknown;
      return typeof value === "function" ? (value as (...a: unknown[]) => unknown).bind(target) : value;
    },
  });
  return {
    sql,
    take() {
      const out = { statements: cursors.length, rowsRead: 0, rowsWritten: 0 };
      for (const cursor of cursors) { out.rowsRead += cursor.rowsRead; out.rowsWritten += cursor.rowsWritten; }
      cursors = [];
      return out;
    },
  };
}

/** ReducerStorage that keeps the last commit report the path took, for K03 finalize's own counters. */
class BenchStorage extends ReducerStorage {
  private lastReport: CommitReport | undefined;
  /** The report the path took since the last `takeLast`. */
  takeLast(): CommitReport | undefined {
    const report = this.lastReport;
    this.lastReport = undefined;
    return report;
  }
  override takeReport(): CommitReport | undefined {
    const report = super.takeReport();
    this.lastReport = report;
    return report;
  }
}

async function sha256(text: string): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text));
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

export class BenchReducerTenant extends DurableObject<BenchEnv> {
  readonly capture = { state: new CaptureState(), wake: new ChangeWake() };
  readonly storage: BenchStorage;
  readonly registry = new ModuleRegistry(PROJECT);
  readonly host: TenantModuleHost;
  readonly reducers: ReducerPath;
  readonly module: ProjectModule;
  private readonly direct: ReturnType<typeof countingSql>;
  private reported: { generation: number; tables: Set<string> } | undefined;
  private roles = new Map<string, string>();
  /** Rows read by `rowReported`'s sqlite_schema scan since the last call report. */
  private reportedRowsRead = 0;
  readonly loadMs: number;

  constructor(ctx: DurableObjectState, env: BenchEnv) {
    super(ctx, env);
    const started = Date.now();
    this.storage = new BenchStorage(ctx.storage, this.capture, { writeTracking: "mixed", rowReported: (table) => this.rowReported(table) });
    // The module as /dev/sync would hand it to the object: the function table and the artifact hash.
    this.module = projectModuleFromManifest(PROJECT, { functions, module: { hash: meta.artifactHash, generation: meta.generation } });
    // Actions are not in the split Reducer bundle: keep them registered (the scheduler accepts them as
    // targets) with a placeholder export, as kernel/host/bench does.
    const exports: ModuleExports = { ...(app as ModuleExports), __action: () => null };
    const artifact = moduleArtifact(this.module, meta.generation, exports);
    this.registry.install({
      ...artifact,
      functions: artifact.functions.map((f) => f.kind === "action" ? { ...f, export: "__action", argsSchema: { kind: "any" }, resultSchema: { kind: "any" } } : f),
    });
    // S2's permission stub (no permissionGrants projection in the Whagons manifest).
    const permissions = { has: (member: string) => ["owner", "admin"].includes(this.roles.get(member) ?? "") };
    this.host = new TenantModuleHost({ storage: this.storage, registry: this.registry, permissions });
    this.direct = countingSql(ctx.storage.sql);
    this.reducers = new ReducerPath({
      storage: this.storage,
      direct: { sql: this.direct.sql, transactionSync: (fn) => ctx.storage.transactionSync(fn) },
      host: this.host,
      module: () => this.module,
      permissions: new PermissionBits(undefined),
      flushReferences: (sql: CaptureSql) => { flushReferences(sql); },
    });
    this.loadMs = Date.now() - started;
  }

  /** tenant.ts `rowReported`: captured entity tables with rowids, once per schema generation. */
  private rowReported(table: string): boolean {
    const generation = this.storage.catalog.generation;
    if (this.reported?.generation !== generation) {
      const cursor = this.ctx.storage.sql.exec<{ name: string; ddl: string | null }>(
        `SELECT t.name AS name, t.sql AS ddl FROM sqlite_schema t
         WHERE t.type = 'table' AND EXISTS (SELECT 1 FROM sqlite_schema g WHERE g.type = 'trigger' AND g.tbl_name = t.name
           AND g.name = '_gonvex_sync_' || t.name || '_insert' AND g.sql LIKE '%AFTER INSERT%')`,
      );
      const rows = cursor.toArray();
      // Outside K01's counters (direct handle): measured separately.
      this.reportedRowsRead += cursor.rowsRead;
      const tables = new Set(rows.filter((row) => !/\bWITHOUT\s+ROWID\b/i.test(row.ddl ?? "")).map((row) => row.name.toLowerCase()));
      this.reported = { generation, tables };
    }
    return this.reported.tables.has(table);
  }

  private schemaChanged(): void {
    this.storage.invalidateSchema();
    this.capture.state.invalidate();
    this.reported = undefined;
  }

  private clock(): { epoch: string; revision: number } | null {
    const row = this.ctx.storage.sql.exec<{ epoch: string; revision: number }>("SELECT epoch, revision FROM _gonvex_sync_clock WHERE singleton = 1").toArray()[0];
    return row ? { epoch: String(row.epoch), revision: Number(row.revision) } : null;
  }

  override async fetch(request: Request): Promise<Response> {
    const url = new URL(request.url);
    const body = request.method === "POST" ? await request.json() as Record<string, unknown> : {};
    const sql = this.ctx.storage.sql;
    switch (url.pathname) {
      case "/provision": {
        const failures: unknown[] = [];
        let executed = 0;
        for (const statement of body["statements"] as { type: string; name: string; sql: string }[]) {
          try { sql.exec(statement.sql); executed++; } catch (error) { failures.push({ type: statement.type, name: statement.name, error: message(error).slice(0, 200) }); }
        }
        for (const { table, rows } of body["rows"] as { table: string; rows: Record<string, unknown>[] }[]) {
          for (const row of rows) {
            const keys = Object.keys(row);
            try {
              sql.exec(`INSERT INTO "${table}" (${keys.map((k) => `"${k}"`).join(",")}) VALUES (${keys.map((_, i) => `?${i + 1}`).join(",")})`, ...keys.map((k) => row[k] as SqlStorageValue));
            } catch (error) { failures.push({ type: "row", name: table, error: message(error).slice(0, 200) }); }
          }
        }
        this.schemaChanged();
        return json({ executed, failures, databaseSize: sql.databaseSize });
      }
      case "/install": {
        // K03's change feed on the provisioned subset, one storage transaction per unit (as K02 chunks it).
        // The plan is read again after the infrastructure unit (installChangeFeed does the same).
        const capture = directSql(sql);
        const applied: { kind: string; receipt: string; statements: number }[] = [];
        const failures: { receipt: string; error: string }[] = [];
        const apply = (unit: InstallUnit) => {
          try {
            this.ctx.storage.transactionSync(() => applyInstallUnit(capture, unit));
            applied.push({ kind: unit.kind, receipt: unit.receipt, statements: unit.statements.length });
          } catch (error) { failures.push({ receipt: unit.receipt, error: message(error).slice(0, 300) }); }
        };
        const started = Date.now();
        let warm: number | string;
        try {
          let plan = planChangeFeedInstall(capture);
          if (plan[0]?.kind === "infrastructure") { apply(plan[0]); plan = planChangeFeedInstall(capture); }
          for (const unit of plan) apply(unit);
          warm = planChangeFeedInstall(capture).length;
        } catch (error) {
          failures.push({ receipt: "<plan>", error: message(error).slice(0, 300) });
          warm = "plan failed";
        }
        this.schemaChanged();
        const triggers = Number(sql.exec("SELECT count(*) AS n FROM sqlite_schema WHERE type='trigger' AND name LIKE '_gonvex_sync_%'").one()["n"]);
        return json({
          units: applied.length, statements: applied.reduce((n, u) => n + u.statements, 0), byKind: applied.reduce<Record<string, number>>((m, u) => ({ ...m, [u.kind]: (m[u.kind] ?? 0) + 1 }), {}),
          failures, warmPlanUnits: warm, captureTriggers: triggers, ms: Date.now() - started, rowsRead: capture.counters.rowsRead, rowsWritten: capture.counters.rowsWritten,
        });
      }
      case "/call": {
        const session = body["session"] as TenantSession;
        const call = body["request"] as ReducerCallRequest;
        // The permission stub reads committed roles before the call (outside its transaction).
        this.roles = new Map(sql.exec("SELECT id, role FROM members").toArray().map((row) => [String(row["id"]), String(row["role"])]));
        this.reducers.lastNumbers = undefined;
        this.direct.take();
        this.reportedRowsRead = 0;
        this.storage.takeLast();
        const started = Date.now();
        const outcome = await this.reducers.serial(() => this.reducers.execute(session, call));
        const serverMs = Date.now() - started;
        const direct = this.direct.take();
        const clock = this.clock();
        let changeRows = 0, changeTables: string[] = [];
        if (outcome.ok && outcome.committedRevision !== undefined) {
          const rev = Math.trunc(outcome.committedRevision);
          changeRows = Number(sql.exec(`SELECT count(*) AS n FROM _gonvex_sync_changes WHERE revision = ${rev}`).one()["n"]);
          changeTables = sql.exec(`SELECT DISTINCT table_name FROM _gonvex_sync_changes WHERE revision = ${rev} ORDER BY 1`).toArray().map((r) => String(r["table_name"]));
        }
        return json({
          ok: outcome.ok,
          result: outcome.ok ? outcome.result : undefined,
          committedRevision: outcome.ok ? outcome.committedRevision ?? null : null,
          error: outcome.ok ? undefined : outcome.failure,
          numbers: this.reducers.lastNumbers ?? null,
          direct, rowReportedRowsRead: this.reportedRowsRead, finalize: this.storage.takeLast()?.capture ?? null, clock, changeRows, changeTables, serverMs,
        });
      }
      case "/snapshot": {
        // Every table in sqlite_schema (sqlite_*, _cf_*, _gonvex_* included) plus the schema itself, as
        // sorted JSON rows and their SHA-256. Nothing is ignored; tables the platform refuses to read are listed.
        const out: Record<string, { rows: number; digest: string }> = {};
        const unreadable: Record<string, string> = {};
        const schemaRows = sql.exec("SELECT type, name, tbl_name, sql FROM sqlite_schema ORDER BY type, name").toArray();
        out["<sqlite_schema>"] = { rows: schemaRows.length, digest: await sha256(JSON.stringify(schemaRows)) };
        const tables = schemaRows.filter((r) => r["type"] === "table").map((r) => String(r["name"]));
        for (const name of tables) {
          try {
            const rows = sql.exec(`SELECT * FROM "${name.replaceAll('"', '""')}"`).toArray()
              .map((row) => JSON.stringify(Object.entries(row).map(([c, v]) => [c, v instanceof ArrayBuffer ? `blob:${[...new Uint8Array(v)].map((b) => b.toString(16).padStart(2, "0")).join("")}` : v])))
              .sort();
            out[name] = { rows: rows.length, digest: await sha256(rows.join("\n")) };
          } catch (error) { unreadable[name] = message(error).slice(0, 200); }
        }
        return json({ tables: out, unreadable });
      }
      case "/receipts": {
        const rows = sql.exec("SELECT subject, idempotency_key, path, result, created_at FROM _gonvex_reducer_idempotency ORDER BY created_at, idempotency_key").toArray();
        return json(rows);
      }
      case "/state": {
        const count = (table: string) => { try { return Number(sql.exec(`SELECT count(*) AS n FROM "${table}"`).one()["n"]); } catch { return null; } };
        return json({
          clock: this.clock(),
          schemaObjects: Number(sql.exec("SELECT count(*) AS n FROM sqlite_schema").one()["n"]),
          changes: count("_gonvex_sync_changes"), transactions: count("_gonvex_sync_transactions"),
          outbox: count("_gonvex_action_outbox"), referenceRules: count("_gonvex_reference_rules"), referencePending: count("_gonvex_reference_pending"),
          referenceRequests: count("_gonvex_reference_requests"), referenceCatalog: count("_gonvex_reference_catalog"),
        });
      }
      case "/meta":
        return json({
          loadMs: this.loadMs, functions: this.registry.activeGeneration?.engine.functions.size, exports: Object.keys(app).length,
          unresolved: this.registry.activeGeneration?.engine.unresolved().length, artifactHash: this.module.artifactHash, permissionGrants: this.module.permissionGrants ?? null,
        });
      default:
        return json({ error: "not found" }, 404);
    }
  }
}

export default {
  fetch(request: Request, env: BenchEnv): Promise<Response> | Response {
    const url = new URL(request.url);
    if (url.pathname === "/ping") return json({ ok: true });
    return env.TENANT.getByName(url.searchParams.get("tenant") ?? "bench").fetch(request);
  },
};
