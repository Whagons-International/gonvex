// Bench Worker: one tenant object that runs the real Whagons Reducer bundle
// through the K07 Reducer path, composed the way `tenant.ts` composes it
// (without K02: the schema is S2's subset, provisioned directly, then K03's
// change feed is installed on it):
//
//   ReducerPath (path.ts) → ReducerStorage (storage.ts: K01 mixed FK tracking,
//   K03 finalize, the receipt) → TenantModuleHost + ModuleRegistry (K04).
//
// Permissions: the Whagons manifest declares no `permissionGrants`, so
// `PermissionBits` has no projection; the K04 host gets S2's stub instead
// (owners and admins hold every permission), as kernel/host/bench does.
