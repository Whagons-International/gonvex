/**
 * Records the Rust runtime's run of `live-query-task-grid` as the golden file
 * the kernel's query engine is replayed against in workerd
 * (cloudflare/kernel/query/test/task-grid-parity.test.ts). K03's
 * `capture-golden.mjs` is the model.
 *
 *   node src/live-query-golden.mjs [--out ../kernel/query/test/golden/rust-task-grid.json] [--work dir]
 *
 * It needs the same `gonvex-runtime` binary and built packages as the harness
 * (README.md, "Running"). It runs the scenario on one Rust backend and
 * writes: the fixture migration, the query functions and visibility plans of
 * the manifest, the tenant's Members, every committed revision of the
 * scenario with its change rows (from `_gonvex_sync_changes`), each action
 * with the revision it saw, and the raw query frames Bob and Carol received
 * and sent, per step. Backend ids are replaced by the harness aliases;
 * `rawIds` maps them back, because each `windowRevision` hashes the real ids.
 */
import { mkdtemp, readFile, rm, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { buildFixture } from './fixture.mjs';
import { RustBackend } from './backends/rust.mjs';
import { runScenario } from './runner.mjs';
import { CONFORMANCE } from './paths.mjs';
import scenario, { RECORDINGS } from '../scenarios/live-query-task-grid.mjs';

const { values } = parseArgs({ options: { out: { type: 'string' }, work: { type: 'string' } } });
const out = resolve(values.out ?? join(CONFORMANCE, '../kernel/query/test/golden/rust-task-grid.json'));
const work = values.work ? resolve(values.work) : await mkdtemp(join(process.env.GONVEX_CONFORMANCE_TMP ?? tmpdir(), 'k08-golden-'));
await mkdir(work, { recursive: true });
const fixtures = { 1: await buildFixture(work, 1) };
const backend = new RustBackend({ name: 'rust', workDir: join(work, 'rust') });
await backend.start();
try {
  const trace = await runScenario({ scenario, backend, fixtures });
  if (trace.failures.length) throw new Error(`scenario failed on Rust:\n${trace.failures.join('\n')}`);
  const record = RECORDINGS.get(backend.name);
  const [project] = backend.keys.keys();
  const tenant = `${scenario.name}-a`;
  const aliases = new Map([[project, '<project>'], [tenant, '<tenant:a>']]);
  for (const [name, ids] of Object.entries(record.members)) {
    aliases.set(ids.accountId, `<account:${name}>`);
    aliases.set(ids.memberId, `<member:${name}@a>`);
  }
  const mask = (value) => {
    let text = JSON.stringify(value);
    for (const [raw, alias] of aliases) text = text.split(raw).join(alias);
    return JSON.parse(text);
  };

  const { DatabaseSync } = await import('node:sqlite');
  const db = new DatabaseSync(join(backend.dataDir, 'projects', project, 'tenants', `${tenant}.db`), { readOnly: true });
  const writes = record.actions.filter(a => a.write).map(a => a.revision);
  const first = Math.min(...writes);
  const clock = db.prepare('SELECT epoch, revision FROM _gonvex_sync_clock WHERE singleton = 1').get();
  const members = db.prepare('SELECT id, account_id, status, role, permissions FROM members ORDER BY id').all();
  const changes = db.prepare(`SELECT revision, ordinal, table_name, row_id, operation, changed_columns, old_value, new_value
    FROM _gonvex_sync_changes WHERE revision >= ? ORDER BY revision, ordinal`).all(first);
  const transactions = db.prepare('SELECT revision, origin_command_id FROM _gonvex_sync_transactions WHERE revision >= ? ORDER BY revision').all(first);
  db.close();
  const revisions = transactions.map(t => ({
    revision: t.revision,
    changes: changes.filter(c => c.revision === t.revision).map(c => ({
      table: c.table_name, rowId: c.row_id, operation: c.operation,
      changedColumns: JSON.parse(c.changed_columns ?? '[]'),
      oldValue: c.old_value === null ? null : JSON.parse(c.old_value),
      newValue: c.new_value === null ? null : JSON.parse(c.new_value),
    })),
  }));
  const unattributed = revisions.map(r => r.revision).filter(r => !writes.includes(r));
  const manifest = fixtures[1].manifest;
  const functions = Object.fromEntries(Object.entries(manifest.functions).filter(([path]) => path.startsWith('tasks.')));
  const golden = {
    about: 'Rust runtime run of cloudflare/conformance/scenarios/live-query-task-grid.mjs. Generated by src/live-query-golden.mjs; do not edit.',
    migration: await readFile(join(CONFORMANCE, 'fixtures/app/migrations/0002_task_grid.sql'), 'utf8'),
    keys: { tasks: '_id', taskGridRows: 'taskId', taskRelatedSearchDocuments: 'taskId', taskWorkspaceContexts: '_id', memberTeams: '_id', taskUsers: '_id', taskFindings: '_id', statuses: '_id', priorities: '_id' },
    functions,
    visibility: manifest.visibility,
    members: mask(members),
    epoch: clock.epoch,
    baseRevision: first - 1,
    unattributed,
    revisions: mask(revisions),
    steps: trace.steps.map(s => s.name),
    actions: mask(record.actions),
    frames: mask(record.frames),
    // Rust hashed results (windowRevision) over the real ids: the parity test restores them to check bytes.
    rawIds: Object.fromEntries([...aliases].map(([raw, alias]) => [alias, raw])),
  };
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, JSON.stringify(golden, null, 1) + '\n');
  const frameCount = Object.values(record.frames).reduce((n, list) => n + list.length, 0);
  console.log(`wrote ${out}: ${revisions.length} revisions (${unattributed.length} not from scenario writes), ${record.actions.length} actions, ${frameCount} query frames`);
} finally {
  await backend.stop();
  if (!values.work) await rm(work, { recursive: true, force: true });
}
