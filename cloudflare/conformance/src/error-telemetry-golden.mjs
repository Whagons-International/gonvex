/**
 * Records the Rust runtime's run of `error-telemetry` as the golden file the
 * kernel's telemetry is replayed against in workerd
 * (cloudflare/kernel/telemetry/test/parity.spec.ts). K08's
 * `live-query-golden.mjs` is the model.
 *
 *   node src/error-telemetry-golden.mjs [--out ../kernel/telemetry/test/golden/rust-error-telemetry.json] [--work dir]
 *
 * It needs the same `gonvex-runtime` binary and built packages as the harness
 * (README.md, "Running"). It writes the scenario's script (every frame each
 * socket role sent), Rust's `error.ack` for every `error.*` frame, how many
 * heartbeats each rate-limit flood got through, and every route response,
 * with backend ids replaced by aliases and run-dependent values scrubbed by
 * the scenario's named rules.
 */
import { mkdtemp, rm, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { buildFixture } from './fixture.mjs';
import { RustBackend } from './backends/rust.mjs';
import { runScenario } from './runner.mjs';
import { CONFORMANCE } from './paths.mjs';
import scenario, { HTTP, RECORDINGS, SCRIPT } from '../scenarios/error-telemetry.mjs';

const { values } = parseArgs({ options: { out: { type: 'string' }, work: { type: 'string' } } });
const out = resolve(values.out ?? join(CONFORMANCE, '../kernel/telemetry/test/golden/rust-error-telemetry.json'));
const work = values.work ? resolve(values.work) : await mkdtemp(join(process.env.GONVEX_CONFORMANCE_TMP ?? tmpdir(), 'k15-golden-'));
await mkdir(work, { recursive: true });
const fixtures = { 1: await buildFixture(work, 1) };
const backend = new RustBackend({ name: 'rust', workDir: join(work, 'rust') });
await backend.start();
try {
  const started = Date.now();
  const trace = await runScenario({ scenario, backend, fixtures });
  const elapsed = Date.now() - started;
  if (trace.failures.length) throw new Error(`scenario failed on Rust:\n${trace.failures.join('\n')}`);
  // The rate-limit floods count what is left of 60 s windows opened at the start.
  if (elapsed > 50_000) throw new Error(`the run took ${elapsed} ms; the rate-limit windows may have rolled over, run it again`);
  const record = RECORDINGS.get(backend.name);
  const aliases = new Map([[record.project, '<project>'], [record.tenant, '<tenant:a>'], [record.account, '<account:alice>']]);
  const mask = (value) => {
    let text = JSON.stringify(value);
    for (const [raw, alias] of aliases) text = text.split(raw).join(alias);
    return JSON.parse(text);
  };
  const golden = {
    about: 'Rust runtime run of cloudflare/conformance/scenarios/error-telemetry.mjs. Generated by src/error-telemetry-golden.mjs; do not edit.',
    script: SCRIPT,
    http: HTTP,
    fingerprintA: record.fingerprintA,
    steps: mask(record.steps),
  };
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, JSON.stringify(golden, null, 1) + '\n');
  const acks = record.steps.reduce((n, step) => n + Object.keys(step.acks ?? {}).length, 0);
  const routes = record.steps.reduce((n, step) => n + Object.keys(step.http ?? {}).length, 0);
  console.log(`wrote ${out}: ${acks} acks, ${routes} route responses, run ${elapsed} ms`);
} finally {
  await backend.stop();
  if (!values.work) await rm(work, { recursive: true, force: true });
}
