/**
 * Records the Rust runtime's change log for the `change-capture` scenario as
 * the golden file the kernel's capture is replayed against in workerd
 * (cloudflare/kernel/capture/test/capture-parity.test.ts).
 *
 *   node src/capture-golden.mjs [--out ../kernel/capture/test/golden/rust-change-capture.json] [--work dir]
 *
 * It needs the same `gonvex-runtime` binary and built packages as the harness
 * (README.md, "Running"). It runs the scenario on one Rust backend, reads the
 * tenant's change log, and writes: the fixture migration, the transactions,
 * each Reducer's outcome, and the comparable change log (the scenario's own
 * `comparableLog`). Backend ids are replaced by the harness aliases, so the
 * file does not change between runs.
 */
import { mkdtemp, readFile, rm, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import { buildFixture } from './fixture.mjs';
import { RustBackend } from './backends/rust.mjs';
import { runScenario } from './runner.mjs';
import { CONFORMANCE } from './paths.mjs';
import scenario, { TRANSACTIONS, comparableLog } from '../scenarios/change-capture.mjs';

const { values } = parseArgs({ options: { out: { type: 'string' }, work: { type: 'string' } } });
const out = resolve(values.out ?? join(CONFORMANCE, '../kernel/capture/test/golden/rust-change-capture.json'));
const work = values.work ? resolve(values.work) : await mkdtemp(join(process.env.GONVEX_CONFORMANCE_TMP ?? tmpdir(), 'k03-golden-'));
await mkdir(work, { recursive: true });
const fixtures = { 1: await buildFixture(work, 1) };
const backend = new RustBackend({ name: 'rust', workDir: join(work, 'rust') });
await backend.start();
try {
  const trace = await runScenario({ scenario, backend, fixtures });
  if (trace.failures.length) throw new Error(`scenario failed on Rust:\n${trace.failures.join('\n')}`);
  const [project] = backend.keys.keys();
  const tenant = `${scenario.name}-a`;
  const raw = await backend.readChangeLog(project, tenant);
  const ours = raw.transactions.filter(t => String(t.origin_command_id).startsWith('k03-'));
  const base = Math.min(...ours.map(t => t.revision)) - 1;
  // The Members' backend ids, as the harness aliases them.
  const members = new Map();
  for (const t of ours) {
    if (t.actor_account_id) members.set(t.actor_account_id, '<account:alice>');
    if (t.actor_member_id) members.set(t.actor_member_id, '<member:alice@a>');
  }
  const mask = (v) => (typeof v === 'string' && members.has(v) ? members.get(v) : v);
  const log = comparableLog({ ...raw, transactions: raw.transactions.map(t => Object.fromEntries(Object.entries(t).map(([k, v]) => [k, mask(v)]))) }, base);
  // Receipts and trigger SQL as Rust installed them: the kernel's Rust-form scripts must hash to the same digests.
  const { DatabaseSync } = await import('node:sqlite');
  const db = new DatabaseSync(join(backend.dataDir, 'projects', project, 'tenants', `${tenant}.db`), { readOnly: true });
  const bootstrap = db.prepare('SELECT name, digest FROM _gonvex_sync_bootstrap ORDER BY name').all();
  const triggers = db.prepare("SELECT tbl_name AS \"table\", name, sql FROM sqlite_schema WHERE type='trigger' AND tbl_name LIKE 'capture%' ORDER BY tbl_name, name").all();
  db.close();
  const replies = trace.steps.find(s => s.name === 'apply the transactions').observations;
  const golden = {
    about: 'Rust runtime change log for cloudflare/conformance/scenarios/change-capture.mjs. Generated by src/capture-golden.mjs; do not edit.',
    migration: await readFile(join(CONFORMANCE, 'fixtures/app/migrations/0001_fixture.sql'), 'utf8'),
    transactions: TRANSACTIONS,
    replies,
    bootstrap,
    triggers,
    log,
  };
  await mkdir(dirname(out), { recursive: true });
  await writeFile(out, JSON.stringify(golden, null, 1) + '\n');
  console.log(`wrote ${out}: ${log.changes.length} change rows in ${log.transactions.length} revisions`);
} finally {
  await backend.stop();
  if (!values.work) await rm(work, { recursive: true, force: true });
}
