import type { LocalSchema } from '@gonvex/local-runtime/schema';
import type { Manifest } from './manifest-types.js';

/** SQL, including its declared relationships, is the model's source of truth.
 * Replica exposure decides delivery and never decides which tables exist. */
export function renderLocalDataModel(schema:LocalSchema,functions:Manifest['functions']):string{
 const quote=(value:string)=>JSON.stringify(value);
 const union=(values:string[])=>values.length?values.map(quote).join(' | '):'never';
 const integerKeys=Object.entries(schema).filter(([,t])=>/INT/i.test(t.columns[t.key]?.type??'')).map(([name])=>name);
 const lines=["// Generated by Gonvex from the migrated SQL schema. Do not edit.","import type {JsonValue} from '@gonvex/protocol';","import type {ApiArgs,ApiResults} from './api';",'export type TableNames=keyof TableRowMap;',`type IntegerKeyTables=${union(integerKeys)};`,"export type Id<T extends TableNames>=(T extends IntegerKeyTables?number:string)&{readonly __tableName:T};","export type Doc<T extends TableNames>=TableRowMap[T];"];
 for(const[kind,title]of [['query','Query'],['reducer','Reducer'],['action','Action']])lines.push(`export type ${title}FunctionPath=${union(Object.entries(functions).filter(([name,f])=>f.kind===kind&&!name.startsWith('__local.')).map(([name])=>name))};`);
 lines.push('export type SyncFunctionPath=never;','export interface TableRowMap{');
 for(const[name,table]of Object.entries(schema)){
  lines.push(` ${quote(name)}:{`);
  for(const[column,definition]of Object.entries(table.columns)){
   const type=definition.type.toUpperCase();
   let value=/JSON/.test(type)?'JsonValue':/BOOL/.test(type)?'boolean':/INT|REAL|DOUB|FLOA|NUMERIC|DECIMAL/.test(type)?'number':'string';
   const relationship=table.foreignKeys?.find(f=>f.columns.length===1&&f.columns[0]===column&&schema[f.targetTable]?.key===f.targetColumns[0]);
   if(column===table.key)value=`Id<${quote(name)}>`;
   else if(relationship)value=`Id<${quote(relationship.targetTable)}>`;
   lines.push(`  ${quote(column)}:${value}${definition.nullable?'|null':''};`);
  }
  lines.push(' };');
 }
 lines.push('}','export type GeneratedFunctionArgs=ApiArgs;','export type GeneratedFunctionResults=ApiResults;','export type GeneratedTableQueryResults={};');
 return lines.join('\n')+'\n';
}
