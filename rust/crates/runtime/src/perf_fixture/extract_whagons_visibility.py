#!/usr/bin/env python3
"""Inputs of the all-plans visibility parity oracle (read-only on Whagons).

    python3 extract_whagons_visibility.py LEGACY_MANIFEST.json V2_WHAGONS_CHECKOUT

LEGACY_MANIFEST is a Whagons gonvex/_generated/manifest.json whose plans are
legacy (unversioned), e.g. `git show ea04e91ce:gonvex/_generated/manifest.json`
(staging before the mask migration). V2_WHAGONS_CHECKOUT is a checkout whose
generated manifest holds the version 2 masks of the same tables, and whose
migrations/0000_sqlite_baseline.sql is the tenant schema.

Writes, next to this script:
  whagons_visibility_all.json  {"legacy": {table: plan}, "v2": {table: plan}}
  whagons_schema_all.sql       CREATE TABLE statements (foreign keys stripped,
                               no indexes) of every table either plan set names.
"""
import json, re, sys
from pathlib import Path

here = Path(__file__).resolve().parent
legacy = json.loads(Path(sys.argv[1]).read_text())["visibility"]
whagons = Path(sys.argv[2])
v2 = json.loads((whagons / "gonvex/_generated/manifest.json").read_text())["visibility"]
if sorted(legacy) != sorted(v2):
    sys.exit("legacy and v2 manifests declare different tables")
if any(p.get("version") == 2 for p in legacy.values()) or any(p.get("version") != 2 for p in v2.values()):
    sys.exit("expected only legacy plans in the first and only v2 plans in the second manifest")

# Physical tables only: set bases, joins, inheritance parents and via tables
# (a `where` constraint's `table` may name a join alias).
referenced = set(legacy)
def collect(node):
    if isinstance(node, dict):
        if node.get("operator") in ("inherits", "inheritsAny"):
            referenced.add(node["table"])
            if isinstance(node.get("via"), dict):
                referenced.add(node["via"]["table"])
        for value in node.values():
            collect(value)
    elif isinstance(node, list):
        for value in node:
            collect(value)
for plans in (legacy, v2):
    for plan in plans.values():
        for definition in plan.get("sets", {}).values():
            referenced.add(definition["table"])
            referenced.update(join["table"] for join in definition.get("joins", []))
        collect(plan["where"])
referenced.discard("members")  # gonvex owns members; Whagons columns added below

baseline = (whagons / "migrations/0000_sqlite_baseline.sql").read_text()
out = ["-- Generated by extract_whagons_visibility.py from Whagons migrations/0000_sqlite_baseline.sql. Do not edit.\n"]
for table in sorted(referenced):
    match = re.search(r'^CREATE TABLE IF NOT EXISTS "?%s"? \((.*?)^\);' % re.escape(table), baseline, re.S | re.M)
    if not match:
        sys.exit(f"no CREATE TABLE for {table}")
    lines = [line.rstrip().rstrip(",") for line in match.group(1).splitlines() if line.strip()]
    lines = [line for line in lines if "FOREIGN KEY" not in line and "REFERENCES" not in line
             and not line.lstrip().startswith("CONSTRAINT") and not line.lstrip().startswith("CHECK")]
    out.append(f'CREATE TABLE IF NOT EXISTS "{table}" (\n' + ",\n".join(lines) + "\n);\n")
for column in re.findall(r'^ALTER TABLE "members" ADD COLUMN ([^\n]*);$', baseline, re.M):
    out.append(f'ALTER TABLE "members" ADD COLUMN {column};\n')
(here / "whagons_schema_all.sql").write_text("".join(out))
(here / "whagons_visibility_all.json").write_text(
    json.dumps({"legacy": legacy, "v2": v2}, sort_keys=True, separators=(",", ":")) + "\n")
print(len(referenced), "tables,", len(legacy), "plans")
