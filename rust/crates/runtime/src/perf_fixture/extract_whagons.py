#!/usr/bin/env python3
"""Regenerates the Whagons-shaped inputs of the perf fixture (read-only on Whagons).

    python3 extract_whagons.py /path/to/whagons-checkout

Writes, next to this script:
  whagons_schema.sql  CREATE TABLE/INDEX statements of the tables the fixture
                      subscriptions and visibility plans touch (foreign keys
                      stripped; the fixture seeds rows without parents).
  whagons_module.json the real replica collection and reducer definitions of
                      the subscriptions a Whagons user opens (bench/whagons/run.ts)
                      and the version 2 visibility plans of their tables.
Bump FIXTURE_VERSION in mod.rs after regenerating.
"""
import json, re, subprocess, sys
from pathlib import Path

whagons = Path(sys.argv[1])
here = Path(__file__).resolve().parent
manifest = json.loads((whagons / "gonvex/_generated/manifest.json").read_text())
module = manifest["module"]

REPLICAS = [
    "presence.list", "workspaces.list", "statuses.statuses", "tags.tags",
    "members.listMembers", "members.listMemberTeams", "taskResources.taskUsers",
    "taskResources.taskTags", "workspacePreferences.workspacePreferences",
    "tasks.recentWorkspaceTasks",
    # The 11th cold-login collection and the 8 of a task detail window.
    "notifications.listNotifications",
    "tasks.get", "taskResources.listTaskNotes", "taskResources.listTaskLogs",
    "taskResources.listTaskViewsByTaskId", "approvals.listTaskApprovals",
    "taskFindings.listForTask", "taskResources.listTaskUsers",
    "customFields.listTaskValues",
]
REDUCERS = ["presence.beat", "presence.transition", "tasks.updateDescription", "tasks.update"]
functions = {path: module["functions"][path] for path in REPLICAS + REDUCERS}
tables = [functions[path]["replica"]["table"] for path in REPLICAS]
visibility = {}
pending = list(tables)
while pending:
    table = pending.pop()
    if table in visibility:
        continue
    visibility[table] = module["visibility"][table]
    def walk(node):
        if isinstance(node, dict):
            if node.get("operator") == "inherits":
                pending.append(node["table"])
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)
    walk(visibility[table])

referenced = set(visibility)
def collect(node):
    if isinstance(node, dict):
        if isinstance(node.get("table"), str):
            referenced.add(node["table"])
        for value in node.values():
            collect(value)
    elif isinstance(node, list):
        for value in node:
            collect(value)
for plan in visibility.values():
    collect({k: v for k, v in plan.items() if k != "permissionTables"})
referenced |= {"priorities", "teams"}
referenced.discard("members")  # gonvex owns the members table; see mod.rs

baseline = (whagons / "migrations/0000_sqlite_baseline.sql").read_text()
out = ["-- Generated by extract_whagons.py from Whagons migrations/0000_sqlite_baseline.sql. Do not edit.\n"]
for table in sorted(referenced):
    match = re.search(r'^CREATE TABLE IF NOT EXISTS "?%s"? \((.*?)^\);' % re.escape(table), baseline, re.S | re.M)
    if not match:
        sys.exit(f"no CREATE TABLE for {table}")
    lines = [line.rstrip().rstrip(",") for line in match.group(1).splitlines() if line.strip()]
    lines = [line for line in lines if "FOREIGN KEY" not in line and "REFERENCES" not in line]
    out.append(f'CREATE TABLE IF NOT EXISTS "{table}" (\n' + ",\n".join(lines) + "\n);\n")
    for index in re.findall(r'^CREATE (?:UNIQUE )?INDEX IF NOT EXISTS [^\n]* ON "?%s"? \([^\n]*;$' % re.escape(table), baseline, re.M):
        out.append(index + "\n")
members = re.findall(r'^ALTER TABLE "members" ADD COLUMN ([^\n]*);$', baseline, re.M)
out.append("-- Whagons columns on the gonvex members table (created before this script runs).\n")
for column in members:
    out.append(f'ALTER TABLE "members" ADD COLUMN {column};\n')
(here / "whagons_schema.sql").write_text("".join(out))

try:
    commit = subprocess.check_output(["git", "-C", str(whagons), "rev-parse", "HEAD"], text=True).strip()
except Exception:
    commit = "unknown"
(here / "whagons_module.json").write_text(json.dumps(
    {"source": f"whagons {commit} gonvex/_generated/manifest.json", "functions": functions,
     "visibility": visibility}, indent=1, sort_keys=True) + "\n")
print("tables:", sorted(referenced))
print("visibility:", sorted(visibility))
